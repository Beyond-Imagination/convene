/**
 * 구체 클래스의 테스트 대역을 만든다. 그 테스트가 실제로 쓰는 메서드만 구현해 넘긴다.
 *
 * Port 인터페이스가 없는 의존성(구체 서비스·어댑터)은 private 필드 때문에 객체 리터럴을
 * 그대로 넘길 수 없다. `as unknown as T`는 그걸 뚫지만 타입 검사를 통째로 버려서
 * 대역이 실제 시그니처와 어긋나도 조용히 통과한다.
 *
 * 본 헬퍼는 캐스팅을 여기 한 줄에 가두고, 호출부에서는 `Partial<T>`로 메서드명·시그니처·
 * 인자 개수를 그대로 검사받는다. 호출 단언이 필요하면 `jest.fn()`을 넘기면 된다.
 */
export const stub = <T>(impl: Partial<T>): T => impl as T;
